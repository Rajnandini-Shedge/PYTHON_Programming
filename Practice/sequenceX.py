#Sequence Datatype
Data1=[10,20,30,40]                        #List
Data2=(10,20,30,40)                        #Tuple
print(type(Data1))
print(type(Data2))

#Set Datatype
Data3={10,20,30,40}                        #Set
print(type(Data3))

#Mapping Datatype
Data4={"A":10,"B":20,"C":30,"D":40}        #Dict
print(type(Data4))

#Text Datatype(str)
Data5="Maharashtra"                        #str
print(type(Data5))
